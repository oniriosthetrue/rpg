"""Tableaux aléatoires d'aide à la création de scénario (stdlib uniquement).

But : casser la répétition des scénarios générés. Le MJ/LLM pioche des **graines
d'inspiration** dans des tableaux thématiques (crochet, PNJ, conflit/twist, saveur),
puis les **réécrit et les tisse** avec le cadrage (ton, durée, piliers) et le
background des PJ. Une graine n'est jamais copiée mot à mot : c'est un déclencheur
d'idée, pas un résultat.

Chaque table compte **100 entrées** (borne cumulée = numéro de ligne, 1..100) pour
maximiser la variété. Les tables sont ordonnées par sous-thèmes (mystère, quête,
menace, social… / antagoniste, allié, ambigu… / trahison, révélation, dilemme… /
rumeur, coutume, objet, météo…) afin de couvrir des angles distincts plutôt que de
variantes redondantes d'une même idée.

Réutilise ``dice.roll_d100`` (liste de couples ``(borne_supérieure, valeur)``, bornes
cumulées jusqu'à 100). Le ``random.Random`` est injecté pour rendre les tirages
reproductibles à la demande — **aucune seed n'est persistée** ici : les tirages sont
jetables (un système de « lore » pourra s'y greffer plus tard).
"""

from __future__ import annotations

import random

from dnd_perso import dice


def _cent(*valeurs: str) -> list[tuple[int, str]]:
    """Construit une table d100 à 100 entrées : la i-ème valeur porte la borne ``i``.

    Garantit par construction la couverture 1..100 et des bornes strictement croissantes
    (attendus par ``dice.roll_d100`` et les tests). Lève ``ValueError`` si le compte n'est
    pas exactement 100.
    """
    if len(valeurs) != 100:
        raise ValueError(f"Table d100 : attendu 100 graines, reçu {len(valeurs)}.")
    return [(i + 1, v) for i, v in enumerate(valeurs)]


